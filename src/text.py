"""Нормализация и лемматизация текстов.

Запросы короткие и морфологически разнообразные («монтаж видеодомофонов» vs
«Монтаж видеодомофона»), поэтому для лексического поиска приводим слова к
начальной форме морфоанализатором pymorphy3 (open-source, работает локально).
Лемматизируем не каждое вхождение, а каждое уникальное слово один раз (кэш) —
так весь корпус обрабатывается за пару минут.
"""
import re
from functools import lru_cache

import pymorphy3

_TOKEN_RE = re.compile(r"[a-zа-я0-9]+")
_morph = pymorphy3.MorphAnalyzer()

# Служебные слова, которые не несут смысла для поиска услуг.
STOP = set(
    """и в во на с со к ко по за из от до о об у для при про без над под а но или
    же ли бы то не ни что как это мы вы я он она они мой ваш наш свой весь все всё
    так там тут где когда очень также т д др""".split()
)


def normalize(s: str) -> str:
    s = (s or "").lower().replace("ё", "е")
    return s


def tokenize(s: str) -> list[str]:
    return _TOKEN_RE.findall(normalize(s))


@lru_cache(maxsize=2_000_000)
def lemma(tok: str) -> str:
    # цифры и латиницу оставляем как есть, русские слова — в нормальную форму
    if tok.isdigit() or not ("а" <= tok[0] <= "я"):
        return tok
    return _morph.parse(tok)[0].normal_form.replace("ё", "е")


def lemmatize(s: str, drop_stop: bool = True) -> str:
    out = []
    for t in tokenize(s):
        if drop_stop and t in STOP:
            continue
        out.append(lemma(t))
    return " ".join(out)


# Шаблонные куски параметров объявления, которые есть почти у всех и только
# шумят в поиске («График работы от 34200», «Тип стоимости за услугу» ...).
_PARAM_NOISE = re.compile(
    r"(График работы (от|до) \d+|Время работы, (с|до) [\d:]+|Время для связи(, дни недели)? \S+( \d+)?|"
    r"Рабочие дни \S+|Тип стоимости за \S+|Начальная цена|Стоимость \d+|Продолжительность [\d.,]+ \S+|"
    r"График работы, дни недели \S+|Дни (пн|вт|ср|чт|пт|сб|вс)\b|Выполняю заказы от \d+|"
    r"Минимальная сумма заказа \d+|Услуга Своя услуга|"
    r"Опыт работы [^A-ZА-Я]+|Берёте ли срочные заказы|Предоплата)"
)


def clean_item_params(s: str) -> str:
    return _PARAM_NOISE.sub(" ", s or "")
